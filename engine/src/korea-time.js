/* 한국 표준시 이력 · 서머타임 · 경도(진태양시) 보정 — 명세서 §3-6
   기록된 출생 벽시계를 실제 순간(UTC)으로 되돌리려면 그 시점에 시행 중이던
   표준자오선과 서머타임을 알아야 한다. 둘 다 한국은 이력이 여러 번 바뀌었다. */

/* 벽시계 비교용 정렬 키 */
const key = (y, m, d, hh = 0, mi = 0) => ((y * 100 + m) * 100 + d) * 10000 + hh * 100 + mi;

/* 표준시 이력: 시행 시작(현지 벽시계) · 표준시 오프셋(분) · 표준자오선(도) */
const STD_ERAS = [
  { from: key(1912, 1, 1), offset: 540, meridian: 135 },   // 일본 표준시 편입
  { from: key(1954, 3, 21), offset: 510, meridian: 127.5 },
  { from: key(1961, 8, 10), offset: 540, meridian: 135 },  // 현행
];
/* 1912 이전은 대한제국 표준시(1908-04-01 시행, UTC+8:30). 그 이전은 경성 지방시(≈+8:27:52)라
   최대 2분 차이가 나지만 시지(2시간 단위) 판정에는 영향이 없어 +8:30으로 일괄 처리. */
const STD_INITIAL = { offset: 510, meridian: 127.5 };

/* 서머타임 시행 구간 [시작, 종료) — 현지 벽시계 기준. 1948~1960은 자정, 1987~88은 02:00/03:00 전환. */
const DST_RANGES = [
  [key(1948, 6, 1), key(1948, 9, 13)],
  [key(1949, 4, 3), key(1949, 9, 11)],
  [key(1950, 4, 1), key(1950, 9, 10)],
  [key(1951, 5, 6), key(1951, 9, 9)],
  [key(1955, 5, 5), key(1955, 9, 9)],
  [key(1956, 5, 20), key(1956, 9, 30)],
  [key(1957, 5, 5), key(1957, 9, 22)],
  [key(1958, 5, 4), key(1958, 9, 21)],
  [key(1959, 5, 3), key(1959, 9, 20)],
  [key(1960, 5, 1), key(1960, 9, 18)],
  [key(1987, 5, 10, 2, 0), key(1987, 10, 11, 3, 0)],
  [key(1988, 5, 8, 2, 0), key(1988, 10, 9, 3, 0)],
];

/* 주요 도시 경도(동경). 경도 보정은 이 값과 표준자오선의 차이에서 나온다. */
export const LONGITUDE = {
  서울: 126.9784, 인천: 126.7052, 수원: 127.0286, 춘천: 127.7295,
  대전: 127.3845, 광주: 126.8526, 대구: 128.6014, 부산: 129.0756, 제주: 126.5312,
};

/* 기록된 벽시계 시점에 적용되던 표준시·서머타임 */
export function koreaTimeLaw(y, m, d, hh = 0, mi = 0) {
  const k = key(y, m, d, hh, mi);
  let era = STD_INITIAL;
  for (const e of STD_ERAS) if (k >= e.from) era = e;
  const dst = DST_RANGES.some(([s, e]) => k >= s && k < e) ? 60 : 0;
  return { stdOffset: era.offset, meridian: era.meridian, dst };
}
